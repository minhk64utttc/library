// Read-only verification of the local demo dataset; password stays in memory.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const { readFile } = require('node:fs/promises');
const assert = require('node:assert/strict');
const base = 'http://localhost:8080';
let browser;
async function main() {
  const credentials = await readFile(process.env.DEMO_CREDENTIALS_FILE, 'utf8');
  const password = credentials.match(/Mật khẩu chung[^\r\n]*: ([^\r\n]+)/)?.[1];
  assert.ok(password, 'Credential file format required');
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext();
  const catalog = await (await context.request.get(`${base}/api/public/records?page=1&pageSize=20`)).json();
  assert.ok(catalog.total >= 100);
  const facets = await (await context.request.get(`${base}/api/public/records/facets`)).json();
  assert.ok(facets.publishers.length >= 12);
  const digital = await (await context.request.get(`${base}/api/digital/public?page=1&pageSize=20`)).json();
  assert.ok(digital.items.length >= 4);
  const file = await context.request.get(`${base}/api/digital/public/${digital.items[0].submissionCode}/file`);
  assert.equal(file.status(), 200); assert.equal((await file.body()).subarray(0, 5).toString(), '%PDF-');
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/login`);
  await page.locator('input[type="email"]').fill('demo.admin@thu-vien.local');
  await page.locator('input[type="password"]').fill(password);
  await page.locator('button[type="submit"]').click();
  await page.waitForURL(`${base}/`);
  await page.goto(`${base}/accounts`);
  await page.locator('.accounts__table tbody tr').first().waitFor();
  const accounts = await (await context.request.get(`${base}/api/accounts?page=1&pageSize=10`)).json();
  assert.ok(accounts.total >= 95);
  const counter = await browser.newContext();
  const counterPage = await counter.newPage();
  await counterPage.goto(`${base}/login`);
  await counterPage.locator('input[type="email"]').fill('demo.circulation@thu-vien.local');
  await counterPage.locator('input[type="password"]').fill(password);
  await counterPage.locator('button[type="submit"]').click();
  await counterPage.waitForURL(`${base}/`);
  await counterPage.goto(`${base}/circulation/loans`);
  await counterPage.locator('#borrower-search').fill('DEMO-THE-0001');
  await counterPage.locator('#borrower-search').press('Enter');
  await counterPage.locator('.loan-selection').first().waitFor();
  await counterPage.locator('#copy-search').fill('DEMO-S001-E1-002');
  await counterPage.locator('#copy-search').press('Enter');
  await counterPage.waitForFunction(() => [...document.querySelectorAll('.loan-selection')].some(el => el.textContent.includes('DEMO-S001-E1-002')));
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ pass: true, publicRecords: catalog.total, publishers: facets.publishers.length, publicDigital: digital.items.length, accounts: accounts.total, demoLogins: 2, scannedCardAndCopy: true, pdfDownload: true, businessWrites: 0 }));
}
main().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
