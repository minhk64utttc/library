// Explicit API fixtures for portal navigation, read-only lists and cancel behavior.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const base = process.env.UX_WEB_URL || 'http://localhost:5174';
let browser;
async function main() {
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  let roles = ['admin'];
  let mutations = 0;
  let logoutShouldFail = true;
  const account = () => ({ id: 'qa-admin', fullName: 'Admin QA', email: 'qa@example.test', roles, mustChangePassword: false });
  const copy = { id: 'copy-1', code: 'QA-COPY', editionId: 'edition-1', locationId: 'loc-1', locationName: 'QA Shelf A', status: 'processing', workTitle: 'QA Book' };
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url());
    if (!url.pathname.startsWith('/api/')) return route.continue();
    if (route.request().method() !== 'GET' && !url.pathname.startsWith('/api/auth/')) mutations++;
    if (url.pathname === '/api/auth/logout') return route.fulfill(logoutShouldFail ? { status: 500, json: { code: 'ERROR', message: 'QA server error' } } : { status: 204 });
    let data;
    if (url.pathname === '/api/auth/me') data = account();
    else if (url.pathname === '/api/me/profile') data = { ...account(), phone: '', contactEmail: '', reminderEmailEnabled: true, photoUrl: null, libraryCard: null, status: 'active' };
    else if (url.pathname === '/api/me/card/activity') data = { activeLoanCount: 0, events: [] };
    else if (url.pathname === '/api/me/workspace') data = [];
    else if (url.pathname === '/api/me/notifications') data = { items: [], unreadCount: 0, total: 0, page: 1, pageSize: 5 };
    else if (url.pathname === '/api/accounts') data = { items: [{ ...account(), readerGroup: 'lecturer', status: 'active', createdAt: '2026-11-20T00:00:00Z' }, { id: 'reader-2', fullName: 'Reader QA', email: 'reader@example.test', roles: ['reader', 'manager', 'inventory'], readerGroup: 'student', status: 'active', createdAt: '2026-11-20T00:00:00Z', mustChangePassword: false }], total: 2, page: 1, pageSize: 20 };
    else if (url.pathname === '/api/holdings/copies') data = { items: [copy], total: 1, page: 1, pageSize: 20 };
    else if (url.pathname === '/api/holdings/locations') data = { items: [{ id: 'loc-1', code: 'A', name: 'QA Shelf A' }, { id: 'loc-2', code: 'B', name: 'QA Shelf B' }], total: 2, page: 1, pageSize: 100 };
    else if (url.pathname === '/api/public/records/facets') data = { subjects: [], authors: [], languages: [{ value: 'vi', count: 2 }], publishers: [] };
    else data = { items: [], total: 0, page: 1, pageSize: 20 };
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(data) });
  });
  const output = path.resolve('artifacts/account-refinement');
  await fs.mkdir(output, { recursive: true });
  await page.goto(`${base}/`);
  const trigger = page.locator('.account-control__trigger');
  await trigger.waitFor();
  await trigger.focus(); await page.keyboard.press('ArrowDown');
  await page.locator('.account-control__panel').waitFor();
  assert.equal(await page.locator('.account-control__panel a[href="/me/loans"]').count(), 0, 'staff-only has no reader switch');
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute('href')), '/account/profile');
  await page.keyboard.press('Escape');
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false');
  assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
  await trigger.click(); await page.locator('h1').click();
  assert.equal(await trigger.getAttribute('aria-expanded'), 'false');
  await trigger.click(); await page.locator('.account-control__panel a[href="/account/profile"]').click();
  await page.waitForURL('**/account/profile');
  await page.locator('.profile-tabs').waitFor();
  assert.equal(await page.locator('.staff-layout').count(), 1, 'employee profile stays in workspace');
  await trigger.click(); await page.locator('.account-control__panel a[href="/account/security"]').click();
  await page.waitForURL('**/account/security');
  assert.equal(await page.locator('.staff-layout .change-password--embedded').count(), 1);
  await trigger.click(); await page.locator('.account-control__logout').click();
  await page.locator('.account-control__panel [role="alert"]').waitFor();
  assert.equal(await page.locator('.account-control__identity strong').textContent(), 'Admin QA', 'failed logout must preserve identity');
  assert.ok(page.url().endsWith('/account/security'));
  await page.keyboard.press('Escape');
  await page.goto(`${base}/accounts`);
  await page.locator('.accounts__table').waitFor();
  assert.equal(await page.locator('.accounts__table select, .accounts__table input').count(), 0, 'rows must be view-only');
  assert.ok((await page.locator('.accounts__table tbody tr').first().innerText()).includes('Không áp dụng'));
  await page.locator('.accounts__filters select').first().selectOption('reader');
  assert.equal(new URL(page.url()).search, '', 'role filter stays draft');
  await page.locator('.accounts__filters button[type="submit"]').click();
  await page.waitForURL('**/accounts?*role=reader*');
  await page.locator('.accounts__header > button').click();
  await page.locator('.accounts__dialog[open]').waitFor();
  assert.equal(await page.locator('.accounts__dialog input[type="checkbox"][value="reader"]').isChecked(), true);
  await page.keyboard.press('Escape');
  await page.locator('.accounts__menu summary').first().click();
  await page.locator('.accounts__menu[open] button').first().click();
  await page.locator('.accounts__dialog[open]').waitFor();
  await page.keyboard.press('Escape');
  assert.equal(mutations, 0, 'opening/cancelling editors must not write data');
  await page.screenshot({ path: path.join(output, 'accounts-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await trigger.click(); await page.locator('.account-control__panel').waitFor();
  const bounds = await page.locator('.account-control__panel').boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390, 'menu fits phone viewport');
  await page.screenshot({ path: path.join(output, 'account-menu-mobile.png') });
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  await page.locator('.notification-bell summary').click();
  await page.locator('.notification-bell[open]').waitFor();
  const notificationBounds = await page.locator('.notification-panel').boundingBox();
  assert.ok(notificationBounds.x >= 0 && notificationBounds.x + notificationBounds.width <= 390, 'notification panel fits phone viewport');
  await page.locator('.staff-layout__context').click();
  assert.equal(await page.locator('.notification-bell[open]').count(), 0);
  roles = ['reader'];
  await page.goto(`${base}/`); await page.waitForURL('**/me/loans');
  assert.equal(await page.locator('.staff-layout').count(), 0);
  await trigger.click();
  assert.equal(await page.locator('.account-control__panel a[href="/"]').count(), 0, 'reader has no staff switch');
  roles = ['reader', 'inventory', 'cataloging'];
  await page.goto(`${base}/`); await trigger.click();
  await page.locator('.account-control__panel a[href="/me/loans"]').click();
  await page.waitForURL('**/me/loans');
  await page.goto(`${base}/me/profile`);
  await page.locator('.profile-tabs button').nth(2).click();
  assert.equal(await page.locator('.profile-security-link').getAttribute('href'), '/me/security', 'dual-role profile must preserve reader context');
  await trigger.click(); await page.locator('.account-control__panel a[href="/"]').click();
  await page.waitForURL(`${base}/`);
  await page.goto(`${base}/holdings`);
  await page.locator('.holdings__table').waitFor();
  assert.equal(await page.locator('.holdings__table select').count(), 0);
  assert.equal(await page.locator('.holdings__editor:visible').count(), 0);
  await page.locator('.holdings__table button').click();
  await page.locator('.holdings__dialog[open] select').first().selectOption('loc-2');
  await page.keyboard.press('Escape');
  assert.equal(mutations, 0, 'cancelling shelf selection must not save');
  await page.screenshot({ path: path.join(output, 'holdings-mobile.png'), fullPage: true });
  await page.goto(`${base}/search`);
  await page.locator('.public-search__quick .secondary').click();
  const filterDialog = page.locator('#search-filter-dialog[open]');
  await filterDialog.waitFor();
  await filterDialog.locator('option[value="vi"]').waitFor({ state: 'attached' });
  assert.ok((await filterDialog.locator('option[value="vi"]').textContent()).includes('Tiếng Việt'));
  await filterDialog.locator('select').nth(2).selectOption('vi');
  await page.keyboard.press('Escape');
  assert.equal(new URL(page.url()).search, '');
  await page.locator('.public-search__quick .secondary').click();
  assert.equal(await filterDialog.locator('select').nth(2).inputValue(), '', 'cancel restores filter draft');
  await filterDialog.locator('select').nth(2).selectOption('vi');
  await filterDialog.locator('button[type="submit"]').click();
  await page.waitForURL('**/search?*language=vi*');
  assert.ok((await page.locator('.public-search__chips').innerText()).includes('Tiếng Việt'));
  await page.locator('.public-search__quick .secondary').click();
  const filterBounds = await filterDialog.boundingBox();
  assert.ok(filterBounds.y >= 0 && filterBounds.y + filterBounds.height <= 844, 'filter panel fits phone viewport');
  await page.screenshot({ path: path.join(output, 'search-filter-mobile.png') });
  await page.keyboard.press('Escape');
  logoutShouldFail = false;
  await trigger.click(); await page.locator('.account-control__logout').click();
  await page.waitForURL('**/login');
  assert.deepEqual(errors, []);
  console.log('PASS portal UI: menu outside/Escape/arrows; staff profile/security context; role switches; read-only accounts and shelves; draft filter apply/cancel; Vietnamese labels; mobile bounds. API fixtures used.');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
