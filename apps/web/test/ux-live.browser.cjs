// Run against the isolated schema created by ux-workflows.integration.cjs,
// with API :3000 and Vite :5173. Never point this at a real user database.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const { PrismaClient } = require('@prisma/client');
const assert = require('node:assert/strict');
const base = process.env.UX_WEB_URL || 'http://localhost:5173';
const fs = require('node:fs/promises');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
assert.match(new URL(process.env.DATABASE_URL).searchParams.get('schema') || '', /^ux_test_/);
const db = new PrismaClient();
let browser;
async function main() {
  const staff = await db.account.findFirstOrThrow({ where: { roles: { some: { role: 'circulation' } } } });
  const edition = await db.edition.findFirstOrThrow();
  const copy = await db.copy.upsert({ where: { code: 'UX-BROWSER-COPY' }, update: {}, create: { code: 'UX-BROWSER-COPY', editionId: edition.id, status: 'available' } });
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/login`);
  await page.locator('input[type="email"]').fill(staff.email);
  await page.locator('input[type="password"]').fill('UxTest-2026-Strong!');
  await page.locator('button[type="submit"]').click();
  await page.waitForURL(`${base}/`);
  await page.locator('.task-card').first().waitFor();
  await page.locator('.account-control__trigger').click();
  await page.locator('.account-control__panel a[href="/account/profile"]').click();
  await page.waitForURL('**/account/profile');
  await page.locator('.staff-layout input[name="fullName"]').waitFor();
  await page.locator('.account-control__trigger').click();
  await page.locator('.account-control__panel a[href="/account/security"]').click();
  await page.waitForURL('**/account/security');
  await page.locator('.staff-layout .change-password--embedded').waitFor();
  await page.goto(`${base}/circulation/loans`);
  await page.locator('#copy-search').fill(copy.code);
  await page.locator('#copy-search').press('Enter');
  await page.waitForFunction(code => [...document.querySelectorAll('.loan-selection')].some(el => el.textContent.includes(code)), copy.code);
  await page.locator('#borrower-search').fill('reader');
  await page.locator('#borrower-search').press('Enter');
  await page.locator('.loan-options').first().waitFor();
  const output = path.resolve('artifacts/ux-review');
  await fs.mkdir(output, { recursive: true });
  await page.screenshot({ path: path.join(output, 'loans-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, 'loans-mobile.png'), fullPage: true });
  const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].filter(el => el.getBoundingClientRect().right > window.innerWidth + 1 && el.getBoundingClientRect().width > 0).slice(0, 15).map(el => el.className));
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, `loans should fit mobile viewport: ${overflow.join(', ')}`);
  assert.equal(await page.locator('.loan-table').evaluate(el => el.scrollWidth > el.clientWidth + 1), false, 'loan cards should fit without a horizontal scroll');
  const loan = await db.loan.findFirstOrThrow({ include: { borrower: true } });
  await db.notification.create({ data: { accountId: loan.borrowerId, loanId: loan.id, dedupeKey: randomUUID(), subject: 'Browser QA reminder', body: 'Isolated test notification', status: 'skipped' } });
  await page.context().clearCookies();
  await page.goto(`${base}/login`);
  await page.locator('input[type="email"]').fill(loan.borrower.email);
  await page.locator('input[type="password"]').fill('UxTest-2026-Strong!');
  await page.locator('button[type="submit"]').click();
  await page.waitForURL('**/me/loans');
  await page.goto(`${base}/me/profile`);
  await page.locator('.notification-bell summary').click();
  const readResponse = page.waitForResponse(response => response.url().endsWith('/api/me/notifications/read') && response.status() === 204);
  await page.locator('.notification-panel > button').click();
  await readResponse;
  await page.waitForFunction(() => !document.querySelector('.notification-count'));
  await page.locator('.notification-bell summary').click();
  await page.locator('.profile-tabs button').nth(1).click();
  await page.locator('.profile-panel').waitFor();
  await page.goto(`${base}/search`);
  await page.locator('.public-search__quick input').fill('UX');
  await page.locator('.public-search__quick button[type="submit"]').click();
  await page.waitForURL('**/search?*q=UX*');
  await page.locator('.public-search__results, .public-search__empty, .public-search__count').first().waitFor();
  const admin = await db.account.findFirstOrThrow({ where: { roles: { some: { role: 'admin' } } } });
  await page.context().clearCookies();
  await page.goto(`${base}/login`);
  await page.locator('input[type="email"]').fill(admin.email);
  await page.locator('input[type="password"]').fill('UxTest-2026-Strong!');
  await page.locator('button[type="submit"]').click();
  await page.waitForURL(`${base}/`);
  await page.goto(`${base}/accounts`);
  await page.locator('.accounts__table').waitFor();
  assert.equal(await page.locator('.accounts__table input, .accounts__table select').count(), 0);
  await page.locator('.accounts__header > button').click();
  await page.locator('.accounts__dialog[open]').waitFor();
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []);
  console.log('PASS live browser: actual login, staff profile/security context, role tasks, code + Enter lookup, borrower suggestions, profile card, notification read 204, URL search, accounts read-only/create cancel, mobile width, no page errors. Isolated PostgreSQL test fixtures.');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); await db.$disconnect(); });
