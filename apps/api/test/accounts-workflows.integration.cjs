// Isolated schema; exercises accounts form payloads and session effects against PostgreSQL.
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { readFileSync, existsSync } = require('node:fs');
const { resolve } = require('node:path');
const { spawnSync } = require('node:child_process');
const root = resolve(__dirname, '../../..');
require('ts-node').register({ project: resolve(root, 'apps/api/tsconfig.json'), transpileOnly: true });
const { PrismaClient } = require('@prisma/client');
const { AccountsService } = require('../src/modules/accounts/accounts.service');
const { SessionService } = require('../src/modules/auth/session.service');
const { verify } = require('@node-rs/argon2');
const { accountCreateSchema, accountUpdateSchema, accountResetPasswordSchema, accountListQuerySchema } = require('@thu-vien/shared');
const envFile = resolve(root, '.env');
const configured = process.env.DATABASE_URL || (existsSync(envFile) ? readFileSync(envFile, 'utf8').match(/^DATABASE_URL=["']?([^\r\n"']+)/m)?.[1] : null);
assert.ok(configured, 'DATABASE_URL is required');
const database = new URL(configured);
database.searchParams.set('schema', `accounts_test_${Date.now()}`);
const env = { ...process.env, DATABASE_URL: database.toString() };
const migrated = spawnSync(process.execPath, [resolve(root, 'node_modules/prisma/build/index.js'), 'migrate', 'deploy', '--schema', 'apps/api/prisma/schema.prisma'], { cwd: root, env, encoding: 'utf8' });
assert.equal(migrated.status, 0, migrated.stderr);
const db = new PrismaClient({ datasources: { db: { url: database.toString() } } });
const clock = { now: () => new Date() };
const sessions = new SessionService(db, clock, { SESSION_TTL_HOURS: 12, SESSION_SECRET: randomUUID() });
const service = new AccountsService(db, sessions, clock);
async function main() {
  const email = `alpha-${randomUUID()}@test.local`;
  const created = await service.create(accountCreateSchema.parse({ email, fullName: 'Accounts Fixture', password: 'Temporary-Strong-2026', roles: ['reader', 'cataloging', 'digital'], readerGroup: 'lecturer', status: 'active', mustChangePassword: true }));
  assert.deepEqual([...created.roles].sort(), ['cataloging', 'digital', 'reader']);
  assert.equal(created.readerGroup, 'lecturer');
  assert.equal(created.mustChangePassword, true);
  assert.ok(!('passwordHash' in created));
  await service.create(accountCreateSchema.parse({ email: `beta-${randomUUID()}@test.local`, fullName: 'Accounts Fixture', password: 'Temporary-Strong-2026', roles: ['admin'], readerGroup: 'other' }));
  const search = query => service.list(accountListQuerySchema.parse(query));
  assert.equal((await search({ q: 'Accounts Fixture' })).total, 2);
  assert.equal((await search({ q: email, role: 'reader', status: 'active' })).items[0].id, created.id);
  assert.equal((await search({ q: email, role: 'admin' })).total, 0);
  const page1 = await search({ q: 'Accounts Fixture', pageSize: 1 });
  const page2 = await search({ q: 'Accounts Fixture', pageSize: 1, page: 2 });
  assert.equal(page1.total, 2);
  assert.notEqual(page1.items[0].id, page2.items[0].id);
  let changed = await service.update(created.id, accountUpdateSchema.parse({ fullName: 'Updated Name', roles: ['reader', 'manager'], readerGroup: 'student' }));
  assert.equal(changed.fullName, 'Updated Name');
  assert.equal(changed.readerGroup, 'student');
  assert.deepEqual([...changed.roles].sort(), ['manager', 'reader']);
  const session = await sessions.create(created.id);
  assert.ok(await sessions.resolve(session.token));
  await service.update(created.id, accountUpdateSchema.parse({ status: 'disabled' }));
  assert.equal(await sessions.resolve(session.token), null, 'locking revokes sessions');
  assert.equal((await search({ status: 'disabled' })).total, 1);
  changed = await service.update(created.id, accountUpdateSchema.parse({ status: 'active' }));
  assert.equal(changed.status, 'active');
  assert.equal(await sessions.resolve(session.token), null, 'unlock does not restore revoked sessions');
  const resetSession = await sessions.create(created.id);
  await service.resetPassword(created.id, accountResetPasswordSchema.parse({ password: 'Replacement-Strong-2026' }));
  assert.equal(await sessions.resolve(resetSession.token), null);
  const persisted = await db.account.findUnique({ where: { id: created.id } });
  assert.equal(persisted.mustChangePassword, true);
  assert.ok(await verify(persisted.passwordHash, 'Replacement-Strong-2026'));
  console.log('PASS accounts: multi-role creation/edit, reader group, filters/pagination, safe DTO, lock/unlock and reset session effects');
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => db.$disconnect());
